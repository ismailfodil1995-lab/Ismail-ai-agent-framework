import os
import sys

# ضبط ترميز UTF-8 للمخرجات لتجنب أخطاء CP1256 على Windows
if sys.platform == "win32":
    sys.stdout.reconfigure(encoding='utf-8')
    sys.stderr.reconfigure(encoding='utf-8')

from tools import AVAILABLE_TOOLS

def test_level_1():
    print("🔍 بدء اختبار أدوات المستوى الأول...\n")
    
    # 1️⃣ اختبار أداة إنشاء PDF
    print("--- [1/4] اختبار أداة توليد الـ PDF ---")
    if "generate_pdf_report" in AVAILABLE_TOOLS:
        pdf_gen = AVAILABLE_TOOLS["generate_pdf_report"]["fn"]
        res_gen = pdf_gen(title="Test Report", content="This is a test PDF content generated by AI Agent.", filename="sample_test.pdf")
        print(f"نتيجة الاختبار: {res_gen}")
    else:
        print("❌ أداة generate_pdf_report غير مسجلة!")

    print("\n" + "="*40 + "\n")

    # 2️⃣ اختبار أداة قراءة الـ PDF
    print("--- [2/4] اختبار أداة قراءة الـ PDF ---")
    if "read_pdf_file" in AVAILABLE_TOOLS:
        pdf_read = AVAILABLE_TOOLS["read_pdf_file"]["fn"]
        if os.path.exists("sample_test.pdf"):
            res_read = pdf_read("sample_test.pdf")
            print(f"المحتوى المستخرج من الـ PDF:\n{res_read}")
        else:
            print("⚠️ ملف الاختبار sample_test.pdf غير موجود لقراءته!")
    else:
        print("❌ أداة read_pdf_file غير مسجلة!")

    print("\n" + "="*40 + "\n")

    # 3️⃣ اختبار أداة تصدير CSV
    print("--- [3/4] اختبار أداة تصدير الـ CSV ---")
    if "export_to_csv" in AVAILABLE_TOOLS:
        csv_exporter = AVAILABLE_TOOLS["export_to_csv"]["fn"]
        sample_data = [
            {"Name": "Ismail", "Role": "AI Developer", "Status": "Active"},
            {"Name": "Client A", "Role": "Lead", "Status": "Qualified"}
        ]
        res_csv = csv_exporter(sample_data, filename_prefix="test_data")
        print(f"نتيجة التصدير: {res_csv}")
    else:
        print("❌ أداة export_to_csv غير مسجلة!")

    print("\n" + "="*40 + "\n")

    # 4️⃣ اختبار أداة قراءة الويب
    print("--- [4/4] اختبار أداة سحب المواقع ---")
    if "scrape_web_page" in AVAILABLE_TOOLS:
        scraper = AVAILABLE_TOOLS["scrape_web_page"]["fn"]
        # موقع سريع وبسيط للاختبار
        res_scrape = scraper("https://example.com")
        print(f"معاينة السحب (أول 200 حرف):\n{res_scrape[:200]}...")
    else:
        print("❌ أداة scrape_web_page غير مسجلة!")

if __name__ == "__main__":
    test_level_1()