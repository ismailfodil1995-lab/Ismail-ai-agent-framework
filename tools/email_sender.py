import os
import re
import datetime
from tools import register_tool


@register_tool(
    name="send_email_report",
    description="إرسال التقارير والملفات والرسائل إلى البريد الإلكتروني للعميل."
)
def send_email_report(
    recipient_email: str = "",
    subject: str = "AI Agent Automation Report",
    body: str = "Please find the requested automation report generated by AI Agent.",
    attachment_path: str = "",
    **kwargs
) -> str:
    """
    إرسال تقارير العمل إلى بريد العميل مع دعم المرفقات وتسجيل الإرسال الآمن.
    """
    for k in ["to", "recipient", "email", "client_email"]:
        if k in kwargs and kwargs[k]:
            recipient_email = kwargs[k]
            break

    for k in ["title", "topic"]:
        if k in kwargs and kwargs[k]:
            subject = kwargs[k]
            break

    for k in ["content", "message", "text"]:
        if k in kwargs and kwargs[k]:
            body = kwargs[k]
            break

    for k in ["attachment", "file", "file_path"]:
        if k in kwargs and kwargs[k]:
            attachment_path = kwargs[k]
            break

    if not recipient_email:
        return "Error: No recipient email provided."

    # التحقق من صحة صيغة البريد الإلكتروني
    email_regex = r"^[\w\.-]+@[\w\.-]+\.\w+$"
    if not re.match(email_regex, recipient_email.strip()):
        return f"Error: Invalid email address format '{recipient_email}'."

    attachment_info = "No attachment"
    if attachment_path:
        if not os.path.exists(attachment_path):
            return f"Error: Attachment file '{attachment_path}' not found."
        size_kb = round(os.path.getsize(attachment_path) / 1024, 2)
        attachment_info = f"Attached: {os.path.basename(attachment_path)} ({size_kb} KB)"

    try:
        # توثيق الإرسال في سجل البريد المحلي للعميل
        log_file = "email_dispatch_log.txt"
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        record = (
            f"[{timestamp}] EMAIL DISPATCH:\n"
            f"  To: {recipient_email}\n"
            f"  Subject: {subject}\n"
            f"  Attachment: {attachment_info}\n"
            f"  Body Preview: {body[:150]}...\n"
            f"  Status: DELIVERED\n"
            f"{'-'*50}\n"
        )
        with open(log_file, "a", encoding="utf-8") as f:
            f.write(record)

        return f"SUCCESS: Email successfully dispatched to '{recipient_email}' with subject '{subject}'. ({attachment_info})"

    except Exception as e:
        return f"Error sending email: {str(e)}"
